const fill = (text, vars = {}) =>
  text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));

// The engine writes its reasons in English; these patterns rebuild them in Urdu.
function explainUr(text, crop) {
  let m;
  if ((m = text.match(/^(.+) before (.+) supplies nitrogen to the cereal$/)))
    return `${crop(m[1])} کے بعد ${crop(m[2])}: پہلی فصل اناج کو نائٹروجن فراہم کرتی ہے`;
  if ((m = text.match(/^(.+) → (.+): same plant family raises pest carry-over$/)))
    return `${crop(m[1])} کے بعد ${crop(m[2])}: ایک ہی پودا خاندان ہونے سے کیڑوں اور بیماریوں کا خطرہ بڑھتا ہے`;
  if ((m = text.match(/^(\d+) bare-fallow season\(s\) leave soil exposed; consider a cover crop$/)))
    return `${m[1]} موسم زمین خالی رہنے سے مٹی کھلی رہتی ہے؛ زمین ڈھانپنے والی فصل لگانے پر غور کریں`;
  if ((m = text.match(/keeps (\d+)% of its score \(climate-robust\)/)))
    return `2041–2050 کے متوقع موسم میں یہ منصوبہ اپنے اسکور کا ${m[1]}% برقرار رکھتا ہے (موسمیاتی طور پر مضبوط)۔`;
  if ((m = text.match(/keeps (\d+)% of its score \((\d+)% drop/)))
    return `2041–2050 کے متوقع موسم میں یہ منصوبہ اپنے اسکور کا ${m[1]}% برقرار رکھتا ہے (${m[2]}% کمی؛ گرمی اور پانی کے لیے حساس فصلوں کا جائزہ لیں)۔`;
  return text; // unknown message: show the original rather than nothing
}

const I18nContext = createContext(null);

function savedLang() {
  try {
    return localStorage.getItem("rotaterra-lang") === "ur" ? "ur" : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(savedLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
    try {
      localStorage.setItem("rotaterra-lang", lang);
    } catch {
      /* storage blocked: the choice just won't be remembered */
    }
  }, [lang]);

  const t = (key, vars) => fill(STRINGS[lang][key] ?? STRINGS.en[key] ?? key, vars);
  const crop = (key) => {
    const name = FARM_KEYS[key] ?? key;
    return lang === "ur" ? CROPS_UR[name] ?? name : name;
  };
  const cropShort = (key) => SHORT[lang][key] ?? crop(key);
  const season = (s) => t(s); // "warm" / "cool"
  const explain = (text) => (lang === "ur" ? explainUr(text, crop) : text);
  const source = (value) =>
    lang === "ur" ? value.replace("fallback (demo values)", "متبادل (نمونہ اقدار)") : value;

  return (
    <I18nContext.Provider value={{ lang, setLang, t, crop, cropShort, season, explain, source }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);
